/** clinicAndPatientLayer's own appointment line; the Pro layer replaces it with the full list. */
const LEGACY_NO_APPOINTMENT = "- معندوش ميعاد جاي.";

const PAST_SHOWN = 5;

function doctorPart(doctor: string): string {
  const d = String(doctor || "").trim();
  return d && d.toLowerCase() !== "any" ? ` مع ${d}` : "";
}

function whoFor(a: ProAppointment, person: ProPerson): string {
  const fromFamily = a.patientId ? person.family.find((f) => f.id === a.patientId)?.name : undefined;
  const name = (fromFamily || a.patientName || "").trim();
  const writer = !!a.patientId && a.patientId === person.patientId;
  if (name) return writer ? `${name} (اللي بيكتب)` : name;
  return writer ? "اللي بيكتب" : "حد على الرقم ده";
}

function upcomingLine(a: ProAppointment, person: ProPerson): string {
  const service = a.service?.trim() ? ` — ${a.service.trim()}` : "";
  return `- ${whoFor(a, person)}: ${arabicDayLabel(a.date)} الساعة ${arabicTimeLabel(a.time)}${doctorPart(a.doctor)}${service}`;
}

function pastLine(a: ProAppointment, person: ProPerson): string {
  const service = a.service?.trim() ? ` (${a.service.trim()})` : "";
  return `- ${whoFor(a, person)}: ${arabicDayLabel(a.date)}${doctorPart(a.doctor)}${service}`;
}

function personLines(person: ProPerson, todayKey?: string): string[] {
  const out: string[] = [];

  if (todayKey?.trim()) {
    out.push(`\nالنهارده ${arabicDayLabel(todayKey.trim())} (${todayKey.trim()}) — استخدم التاريخ ده لما تحسب from و to في find_slots.`);
  }

  out.push("\nالناس على الرقم ده (الـ id للأدوات بس):");
  if (!person.family.length) {
    out.push("- الرقم ده مش مربوط بأي ملف عندنا.");
  } else {
    for (const f of person.family) {
      out.push(`- ${f.name || "بدون اسم"} [${f.id}]${f.id === person.patientId ? " ← ده اللي بيكتب" : ""}`);
    }
    if (!person.patientId) {
      out.push("- مش معروف مين فيهم اللي بيكتب: لو محتاج تعرف (حجز، ملف، حساب) اسأله بلطف.");
    }
  }

  out.push("\nالمواعيد الجاية على الرقم ده (من الجدول نفسه، حتى اللي الاستقبال حجزها بالتليفون):");
  if (person.upcoming.length) {
    for (const a of person.upcoming) out.push(upcomingLine(a, person));
  } else if (!person.degraded) {
    out.push("- مفيش أي ميعاد جاي لحد على الرقم ده.");
  }
  if (person.degraded) {
    out.push(
      "- ⚠️ النظام مقدرش يراجع كل الحجوزات على الرقم ده دلوقتي، فالقايمة دي ممكن تكون ناقصة. ممنوع تقول للمريض إن معندوش ميعاد أو تفترض ده: لو عايز يحجز أو بيسأل عن ميعاده، اسأله الأول لو عنده ميعاد محجوز، ولو الموضوع محتاج تأكيد اختار handoff_other.",
    );
  }

  const past = person.past.slice(0, PAST_SHOWN);
  if (past.length) {
    out.push("\nآخر زيارات اتعملت فعلاً:");
    for (const a of past) out.push(pastLine(a, person));
  }
  return out;
}

/**
 * The per-turn layer: the standard clinic/patient layer with the old pre-picked slots, booking
 * step and one-line appointment taken out, then everyone on the number, every upcoming
 * appointment, the last real visits, and the memory — in that order.
 *
 * `extra.todayKey` (YYYY-MM-DD, clinic time) lets the model compute find_slots dates; the brain
 * passes it. It lives here, never in the rulebook, so the rulebook stays cacheable.
 */
export function proTurnLayer(input: BotPromptInput, person: ProPerson, extra?: { todayKey?: string }): string {
  const base = clinicAndPatientLayer({
    ...input,
    // Pro is always the selling brain; "assisted" would drop the medicines and media lists.
    mode: "sales",
    offeredSlots: [],
    bookingStep: undefined,
    memory: undefined,
    patient: input.patient ? { ...input.patient, upcomingAppointment: undefined } : undefined,
  }).filter((line) => line !== LEGACY_NO_APPOINTMENT);

  const memory = input.memory?.trim();
  return [
    ...base,
    ...personLines(person, extra?.todayKey),
    memory ? `\nذاكرة من محادثات سابقة مع المريض ده (ابدأ من مكان ما وقفتوا، ومتعيدش اللي هو عارفه):\n${memory.slice(0, 900)}` : "",
  ]
    .filter(Boolean)
    .join("\n");
}
