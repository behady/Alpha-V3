export type SAKey = keyof typeof WORDS.en;

export function useSuperAdminText() {
  const { language, isRTL, toggleLanguage } = useLanguage();
  const isAr = language === "ar";
  const locale = isAr ? "ar-EG" : "en-GB";

  const t = (key: SAKey, vars?: Record<string, string | number>) => {
    let s: string = WORDS[isAr ? "ar" : "en"][key] ?? WORDS.en[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
  const num = (n: number) => Math.round(n).toLocaleString(locale);
  /** "5 days" / "٥ أيام": Arabic counts take a different noun form for 1, 2, 3–10 and 11+. */
  const days = (n: number) => {
    if (!isAr) return n === 1 ? "1 day" : `${num(n)} days`;
    if (n === 1) return "يوم واحد";
    if (n === 2) return "يومان";
    return n >= 3 && n <= 10 ? `${num(n)} أيام` : `${num(n)} يومًا`;
  };
  const money = (n: number) => `$${Math.round(n).toLocaleString(locale)}`;
  // en-GB writes September as "Sept"; en-US keeps the three-letter month.
  const date = (d: Date) => d.toLocaleDateString(isAr ? locale : "en-US", { day: "numeric", month: "short", year: "numeric" });

  return { t, num, days, money, date, isAr, isRTL, locale, toggleLanguage };
}
